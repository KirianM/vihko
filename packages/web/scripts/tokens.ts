// Generates src/theme/tokens.css from src/theme/tokens.json, a copy of the
// Claude Design design system (https://claude.ai/artifact/RaWutTmAdYUCikhz3M2BaV),
// which is the source of truth. If the system changes, copy its tokens.json
// here again and run `npm run build`.
//
// Themes: light in :root; dark if the OS requests it and the person hasn't
// chosen light, or if they've chosen dark (data-theme on <html>). Any token
// whose value is one per theme (`{ light, dark }`), in any family, is set per
// theme; a single value is the same in every theme.
import { readFileSync, writeFileSync } from 'node:fs'

type Value = string | number
type ThemeValue = Value | Record<string, Value>
interface Token { name: string; value: ThemeValue }
interface Tokens {
  color: { themes: { id: string }[]; tokens: Token[] }
  type: { families: Record<string, string> }
  [family: string]: unknown
}

const dir = new URL('../src/theme/', import.meta.url)
const t = JSON.parse(readFileSync(new URL('tokens.json', dir), 'utf8')) as Tokens
const [light, dark] = t.color.themes.map((x) => x.id)
const perTheme = (v: ThemeValue): v is Record<string, Value> => typeof v === 'object'
const pick = (v: ThemeValue, theme: string) => (perTheme(v) ? (v[theme] ?? v[light!]!) : v)

const themed = [...t.color.tokens]
const plain: string[] = []
for (const [family, body] of Object.entries(t)) {
  if (['name', 'version', 'color', 'type'].includes(family)) continue
  for (const k of (body as { tokens: Token[] }).tokens) {
    if (perTheme(k.value)) themed.push(k)
    else plain.push(`  --${k.name}: ${k.value};`)
  }
}
const decl = (theme: string) => themed.map((k) => `  --${k.name}: ${pick(k.value, theme)};`).join('\n')
for (const [key, stack] of Object.entries(t.type.families)) plain.push(`  --font-${key}: ${stack};`)

const css = `/* Generated by scripts/tokens.ts from tokens.json. Do not edit by hand. */
:root {
  color-scheme: light;
${decl(light!)}
${plain.join('\n')}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${decl(dark!).replace(/^/gm, '  ')}
  }
}
:root[data-theme="dark"] {
  color-scheme: dark;
${decl(dark!)}
}
`
writeFileSync(new URL('tokens.css', dir), css)
console.log(`tokens.css: ${themed.length} tokens per theme, ${plain.length} shared`)
